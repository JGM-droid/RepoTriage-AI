"""Deterministic, platform-independent content hashing for evaluation
fixtures.

CI investigation (Milestone 2.7 correction): `adversarial_cases.json` was
authored on Windows via a Python text-mode file write, which introduced
CRLF line endings into the working-tree file; committing it (with Git's
`core.autocrlf=true` normalizing the staged blob to LF) left the checked-in
git blob LF-only while the Windows working-tree copy stayed CRLF. The
checked-in baseline's `adversarial_fixture_hash` was generated by hashing
the Windows working-tree file's *raw bytes* (CRLF) -- so a fresh Linux
checkout of the exact same, semantically-unchanged git blob (LF) hashed
differently, and `python -m app.evaluation` correctly (if confusingly)
raised `BaselineIncompatibleError` in CI. Hashing raw file bytes is
inherently platform-dependent: line endings, and also indentation, key
order, and trailing whitespace, can all change a file's bytes without
changing anything the fixture actually means.

`canonical_json_hash` fixes this at the root: it hashes a canonical
re-serialization of the *parsed* JSON data, never the raw bytes. Two files
that parse to the same data always hash identically regardless of
platform or formatting, while any real content change still changes the
hash -- fixture-change detection is preserved exactly, not weakened.
"""

from __future__ import annotations

import hashlib
import json


def canonical_json_hash(data: object) -> str:
    """SHA-256 of `data`'s canonical JSON form: keys sorted, compact
    separators (no incidental whitespace), ASCII-only escaping (no
    encoding ambiguity). Invariant to CRLF/LF, indentation, key order, and
    trailing whitespace in whatever file `data` was originally parsed
    from; sensitive to any actual change in the data itself."""
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()
