def test_fixture_content_hash_changes_with_a_real_content_change(tmp_path) -> None:
    _, original_hash = load_adversarial_fixture()
    raw = DEFAULT_ADVERSARIAL_FIXTURE_PATH.read_text(encoding="utf-8")
    tampered_path = tmp_path / "tampered.json"
    # A real content change: alter a value, not a structural key -- the
    # fixture must remain schema-valid so this proves the hash reacts to
    # content, not merely to "the file failed to parse".
    tampered_path.write_text(
        raw.replace('"fixture_version": "1.0.0"', '"fixture_version": "1.0.1"'), encoding="utf-8"
    )

    _, tampered_hash = load_adversarial_fixture(tampered_path)

    assert tampered_hash != original_hash


def test_fixture_content_hash_is_invariant_to_line_endings(tmp_path) -> None:
    """CI investigation (Milestone 2.7 correction): the checked-in
    baseline was generated by hashing this fixture's raw Windows (CRLF)
    working-tree bytes, while Linux CI checks out the same, semantically
    identical git blob as LF -- a spurious BaselineIncompatibleError, not
    a real fixture change. The hash must be identical either way."""
    _, real_hash = load_adversarial_fixture()
    raw_bytes = DEFAULT_ADVERSARIAL_FIXTURE_PATH.read_bytes()
    lf_bytes = raw_bytes.replace(b"\r\n", b"\n")
    crlf_bytes = lf_bytes.replace(b"\n", b"\r\n")

    lf_path = tmp_path / "lf.json"
    crlf_path = tmp_path / "crlf.json"
    lf_path.write_bytes(lf_bytes)
    crlf_path.write_bytes(crlf_bytes)

    _, lf_hash = load_adversarial_fixture(lf_path)
    _, crlf_hash = load_adversarial_fixture(crlf_path)

    assert lf_hash == crlf_hash == real_hash


